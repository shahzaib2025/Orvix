function load(file) {
  const built = esbuild.buildSync({ entryPoints: [path.join(__dirname, '../src', file)], bundle: true, platform: 'node', format: 'cjs', write: false, logLevel: 'silent' });
  const loaded = new Module(path.join(__dirname, '.browser-voice-check.cjs'), module); loaded.filename = path.join(__dirname, '.browser-voice-check.cjs'); loaded.paths = module.paths;
  loaded._compile(built.outputFiles[0].text, loaded.filename); return loaded.exports;
}
