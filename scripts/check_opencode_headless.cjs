test('task switching reuses warm preparation and evicts older idle workers', async t => {
  const { createOpenCodeWorkers } = require('../electron/agent/opencode-workers.cjs');
  const created = [];
  const manager = createOpenCodeWorkers('fixture', { create: (_, options) => {
    const fixture = service(t, { ...options, idleMs: 1000 });
    created.push(fixture);
    return fixture.runtime;
  } });
  t.after(() => manager.shutdown());
  await manager.setKeepAlive(true, 'task-a');
  const a = created[1];
  assert.equal(a.requests.some(item => item.url.includes('/experimental/tool')), false, 'enabling availability does not prepare an unknown workspace');
  await manager.connectTask('task-a', undefined, undefined, 'opencode/fixture-free');
  const initialRequests = a.requests.length;
  const initialPid = a.runtime.status().pid;
  await manager.connectTask('task-b', undefined, undefined, 'opencode/fixture-free');
  const b = created[2];
  assert.equal(a.runtime.status().prepared, true);
  const deadline = a.runtime.status().idleExpiresAt;
  assert.ok(deadline > Date.now(), 'leaving a task schedules a grace period instead of stopping it');
  await manager.connectTask('task-b', undefined, undefined, 'opencode/fixture-free');
  assert.equal(a.runtime.status().idleExpiresAt, deadline, 'repeated preparation of the focused task cannot extend another task lifetime');
  await manager.connectTask('task-a', undefined, undefined, 'opencode/fixture-free');
  assert.equal(a.runtime.status().pid, initialPid);
  assert.equal(a.requests.length, initialRequests, 'returning to a prepared worker performs no startup or preparation requests');
  await manager.connectTask('task-c', undefined, undefined, 'opencode/fixture-free');
  assert.equal(b.runtime.status().running, false, 'a third task evicts the older warm worker');
  assert.equal(a.runtime.status().prepared, true);
  a.runtime.retireIdle();
  await manager.connectTask('task-a', undefined, undefined, 'opencode/fixture-free');
  assert.notEqual(a.runtime.status().pid, initialPid, 'a stopped worker genuinely starts and prepares again');
  assert.equal(a.runtime.status().prepared, true);
});
